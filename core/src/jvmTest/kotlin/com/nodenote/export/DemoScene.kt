package com.nodenote.export

import java.awt.BasicStroke
import java.awt.Color
import java.awt.GradientPaint
import java.awt.RadialGradientPaint
import java.awt.RenderingHints
import java.awt.image.BufferedImage
import java.io.ByteArrayOutputStream
import javax.imageio.ImageIO
import kotlin.math.sqrt

/** A small node map that uses every scene item (and every image path); shared by the JVM tests. */
internal object DemoScene {
    private const val INK = 0xFF101828
    private const val MUTED = 0xFF667085
    private const val BORDER = 0xFFD0D5DD
    private const val EDGE = 0xFF98A2B3

    init {
        System.setProperty("java.awt.headless", "true")
    }

    fun build(): Scene {
        val items = mutableListOf<SceneItem>()

        // Header: letter-spaced bold label, title, right-aligned date.
        items += SceneText(32f, 40f, "SHOP BOARD", 11f, MUTED, bold = true, letterSpacing = 1.5f)
        items += SceneText(32f, 68f, "Process improvement map", 22f, INK, bold = true)
        items += SceneText(928f, 40f, "Exported 2 Oct 2026", 11f, MUTED, anchor = TextAnchor.End)

        // Edges first so the cards sit on top of them.
        items += arrow(260f, 300f, 430f, 210f, EDGE, dash = null)
        items += arrow(700f, 300f, 530f, 210f, EDGE, dash = listOf(6f, 4f))

        // Goal card with a type pill and an importance badge.
        card(items, 360f, 110f, 240f, 96f)
        items += SceneRect(376f, 124f, 52f, 18f, radius = 9f, fill = 0xFFEEF4FF)
        items += SceneText(402f, 136.5f, "GOAL", 9f, 0xFF3538CD, bold = true, letterSpacing = 1f, anchor = TextAnchor.Middle)
        items += SceneText(376f, 166f, "20M in two years", 16f, INK, bold = true)
        items += SceneText(376f, 186f, "Revenue target — both shifts", 11f, MUTED)
        items += SceneCircle(588f, 122f, 13f, fill = 0xFFF04438, stroke = 0xFFFFFFFF, strokeWidth = 2f)
        items += SceneText(588f, 126.5f, "9", 12f, 0xFFFFFFFF, bold = true, anchor = TextAnchor.Middle)

        // Left card: JPEG photo, wrapped description.
        card(items, 120f, 300f, 280f, 210f)
        items += SceneImage(136f, 316f, 248f, 100f, jpeg(248, 100, gray = false))
        items += SceneText(136f, 440f, "Inefficiencies", 15f, INK, bold = true)
        paragraph(
            items, 136f, 460f, 248f,
            "Café — “quoted” it’s … € • naïve. Machines idle waiting for setup sheets; the VF-2 warm-up eats the first hour.",
            maxLines = 3,
        )

        // Right card: selected (translucent dashed highlight), PNG avatar with alpha, gray JPEG stored
        // sideways with an EXIF orientation, and a PNG without pixels (PDF placeholder).
        items += SceneRect(548f, 288f, 304f, 234f, radius = 18f, fill = 0x1A2E90FA, stroke = 0xFF2E90FA, strokeWidth = 1.5f, dash = listOf(6f, 4f))
        card(items, 560f, 300f, 280f, 210f)
        val (avatarPng, avatarArgb) = avatar(48)
        items += SceneImage(776f, 316f, 48f, 48f, avatarPng, avatarArgb, 48, 48)
        items += SceneImage(576f, 316f, 64f, 48f, jpeg(64, 48, gray = true, rotated = true))
        items += SceneImage(656f, 316f, 64f, 48f, avatarPng) // no pixels: placeholder in the PDF
        items += SceneText(576f, 390f, "Employees aren't motivated", 15f, INK, bold = true)
        paragraph(
            items, 576f, 410f, 248f,
            "Nobody owns the 5S board, wins never get celebrated, and the second shift hears about changes last. " +
                "Ask the crew what would make Mondays easier and actually follow up on it every single week.",
            maxLines = 3,
        )
        items += SceneLine(576f, 470f, 824f, 470f, BORDER, width = 1f, roundCap = false)
        items += SceneText(576f, 490f, "Not in WinAnsi (PDF shows ?): 漢字 😀", 10f, MUTED)

        // Footer: a translucent band and centered text.
        items += SceneRect(0f, 556f, 960f, 44f, fill = 0x0D101828)
        items += SceneText(480f, 583f, "Generated by NodeNote — vector export sample", 11f, MUTED, anchor = TextAnchor.Middle)

        return Scene(960f, 600f, items, background = 0xFFF5F6F8, title = "NodeNote export sample — Shop board")
    }

    private fun card(items: MutableList<SceneItem>, x: Float, y: Float, w: Float, h: Float) {
        items += SceneRect(x + 1f, y + 2f, w, h, radius = 14f, fill = 0x14101828) // soft shadow
        items += SceneRect(x, y, w, h, radius = 14f, fill = 0xFFFFFFFF, stroke = BORDER, strokeWidth = 1.5f)
    }

    private fun paragraph(items: MutableList<SceneItem>, x: Float, y: Float, width: Float, text: String, maxLines: Int) {
        Helvetica.wrap(text, width, 11f, maxLines = maxLines).forEachIndexed { i, line ->
            items += SceneText(x, y + i * 15f, line, 11f, MUTED)
        }
    }

    private fun arrow(x1: Float, y1: Float, x2: Float, y2: Float, color: Long, dash: List<Float>?): List<SceneItem> {
        val len = sqrt((x2 - x1) * (x2 - x1) + (y2 - y1) * (y2 - y1))
        val ux = (x2 - x1) / len
        val uy = (y2 - y1) / len
        val size = 11f
        val bx = x2 - ux * size
        val by = y2 - uy * size
        return listOf(
            SceneLine(x1, y1, bx, by, color, width = 2f, dash = dash),
            ScenePolygon(listOf(x2, y2, bx - uy * size / 2, by + ux * size / 2, bx + uy * size / 2, by - ux * size / 2), color),
        )
    }

    /**
     * A JPEG made with javax.imageio: a gradient with a few shapes (3 components, or 1 when [gray]).
     * When [rotated], the pixels are stored turned 90° left with EXIF orientation 6, like a phone
     * photo, so it should still display upright.
     */
    fun jpeg(width: Int, height: Int, gray: Boolean, rotated: Boolean = false): ByteArray {
        val type = if (gray) BufferedImage.TYPE_BYTE_GRAY else BufferedImage.TYPE_INT_RGB
        val img = BufferedImage(width, height, type)
        val g = img.createGraphics()
        g.setRenderingHint(RenderingHints.KEY_ANTIALIASING, RenderingHints.VALUE_ANTIALIAS_ON)
        g.paint = GradientPaint(0f, 0f, Color(0x2E90FA), width.toFloat(), height.toFloat(), Color(0xF79009))
        g.fillRect(0, 0, width, height)
        g.color = Color(255, 255, 255, 200)
        g.fillOval(width / 8, height / 5, height / 2, height / 2)
        g.stroke = BasicStroke(3f)
        g.color = Color(0x101828)
        g.drawLine(0, height - 8, width, height / 3)
        g.dispose()
        val stored = if (!rotated) img else BufferedImage(height, width, type).also { turned ->
            val pixel = IntArray(img.raster.numBands)
            for (y in 0 until height) for (x in 0 until width) turned.raster.setPixel(y, width - 1 - x, img.raster.getPixel(x, y, pixel))
        }
        val out = ByteArrayOutputStream()
        check(ImageIO.write(stored, "jpg", out)) { "no JPEG writer" }
        val bytes = out.toByteArray()
        return if (!rotated) bytes else bytes.copyOfRange(0, 2) + EXIF_ORIENTATION_6 + bytes.copyOfRange(2, bytes.size)
    }

    /** APP1 segment: "Exif\0\0", big-endian TIFF header, IFD0 with Orientation (0x0112, SHORT) = 6. */
    private val EXIF_ORIENTATION_6 = listOf(
        0xFF, 0xE1, 0x00, 34, 0x45, 0x78, 0x69, 0x66, 0, 0,
        0x4D, 0x4D, 0x00, 0x2A, 0, 0, 0, 8,
        0x00, 0x01, 0x01, 0x12, 0x00, 0x03, 0, 0, 0, 1, 0x00, 0x06, 0, 0, 0, 0, 0, 0,
    ).map { it.toByte() }.toByteArray()

    /** A round PNG avatar with transparent corners, plus its decoded ARGB pixels. */
    fun avatar(size: Int): Pair<ByteArray, IntArray> {
        val img = BufferedImage(size, size, BufferedImage.TYPE_INT_ARGB)
        val g = img.createGraphics()
        g.setRenderingHint(RenderingHints.KEY_ANTIALIASING, RenderingHints.VALUE_ANTIALIAS_ON)
        val r = size / 2f
        g.paint = RadialGradientPaint(r * 0.7f, r * 0.7f, r, floatArrayOf(0f, 1f), arrayOf(Color(0x7A5AF8), Color(0x3E1C96)))
        g.fillOval(0, 0, size, size)
        g.color = Color(255, 255, 255, 140)
        g.fillOval(size / 4, size / 4, size / 2, size / 2)
        g.dispose()
        val out = ByteArrayOutputStream()
        check(ImageIO.write(img, "png", out)) { "no PNG writer" }
        return out.toByteArray() to img.getRGB(0, 0, size, size, null, 0, size)
    }
}
